  var descMeta = document.querySelector('meta[name="description"]');
  nodes.forEach(function (el) { originals[el.getAttribute('data-i18n')] = el.innerHTML; });
  ariaNodes.forEach(function (el) { originals['aria:' + el.getAttribute('data-i18n-aria')] = el.getAttribute('aria-label'); });
  originals._title = document.title;
  originals._desc = descMeta ? descMeta.getAttribute('content') : '';

  function apply(lang) {
    var d = T[lang] || {};
    nodes.forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      el.innerHTML = d[k] !== undefined ? d[k] : originals[k];
    });
    ariaNodes.forEach(function (el) {
      var k = el.getAttribute('data-i18n-aria');
      el.setAttribute('aria-label', d[k] !== undefined ? d[k] : originals['aria:' + k]);
    });
    document.title = d._title || originals._title;
    if (descMeta) descMeta.setAttribute('content', d._desc || originals._desc);
    document.documentElement.lang = lang;
  }

  function detect() {
    try { var saved = localStorage.getItem(KEY); if (SUPPORTED.indexOf(saved) !== -1) return saved; } catch (e) {}
    var nav = (navigator.language || 'it').slice(0, 2).toLowerCase();
    return SUPPORTED.indexOf(nav) !== -1 ? nav : 'it';
  }

